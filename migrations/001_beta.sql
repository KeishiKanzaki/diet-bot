-- Run in Supabase SQL Editor after taking a backup of existing users / food_logs.
-- Matched to the production preflight supplied 2026-10-19:
-- users.user_id text PK, user_name nullable text; food_logs.calorie nullable integer,
-- food_logs.created_at non-null timestamptz default now(), id bigint identity PK.
begin;
create table if not exists public.users (
  user_id text primary key, user_name text not null default 'Guest',
  target_weight numeric default 0, current_weight numeric default 0
);
alter table public.users add column if not exists consent_version text;
alter table public.users add column if not exists consented_at timestamptz;
-- A duplicate user_id aborts the transaction instead of silently merging records.
create unique index if not exists users_user_id_unique on public.users(user_id);
create table if not exists public.food_logs (
  id bigint generated by default as identity primary key,
  user_id text not null, food_name text not null, calorie integer not null,
  created_at timestamptz not null default now()
);
alter table public.food_logs add column if not exists message_id text;
alter table public.food_logs add column if not exists protein numeric;
alter table public.food_logs add column if not exists fat numeric;
alter table public.food_logs add column if not exists carbs numeric;
create unique index if not exists food_logs_message_id_unique on public.food_logs(message_id);
create index if not exists food_logs_user_time on public.food_logs(user_id, created_at);
create table if not exists public.ai_usage (
  event_id text primary key, user_id text not null,
  created_at timestamptz not null default now()
);
create index if not exists ai_usage_user_time on public.ai_usage(user_id, created_at);
alter table public.users enable row level security;
alter table public.food_logs enable row level security;
alter table public.ai_usage enable row level security;
-- Backend service_role only. Remove pre-existing broad API grants as well as enabling RLS.
revoke all on public.users, public.food_logs, public.ai_usage from public, anon, authenticated;
grant all on public.users, public.food_logs, public.ai_usage to service_role;
-- Supabase service_role normally has sequence access; verify for pre-existing tables.

create or replace function public.accept_nutrition_consent(p_user_id text)
returns void language plpgsql security definer set search_path = public as $$
begin
  if p_user_id is null or p_user_id = '' then raise exception 'user required'; end if;
  perform pg_advisory_xact_lock(hashtextextended(p_user_id, 0));
  insert into users(user_id, user_name, consent_version, consented_at)
    values(p_user_id, 'Guest', '2026-10-18', now())
  on conflict(user_id) do update
    set consent_version=excluded.consent_version, consented_at=excluded.consented_at
    where users.consent_version is distinct from excluded.consent_version or users.consented_at is null;
end $$;
revoke all on function public.accept_nutrition_consent(text) from public, anon, authenticated;
grant execute on function public.accept_nutrition_consent(text) to service_role;

create or replace function public.reserve_ai_usage(p_user_id text, p_event_id text, p_limit integer)
returns text language plpgsql security definer set search_path = public as $$
declare day_start timestamptz := date_trunc('day', now() at time zone 'Asia/Tokyo') at time zone 'Asia/Tokyo';
begin
  if p_limit < 1 or p_limit > 1000 or p_event_id is null or p_user_id is null then
    raise exception 'invalid reservation';
  end if;
  perform pg_advisory_xact_lock(hashtextextended(p_user_id, 0));
  if not exists(select 1 from users where user_id=p_user_id and consent_version='2026-10-18') then
    raise exception 'consent required';
  end if;
  if exists(select 1 from ai_usage where event_id=p_event_id) then return 'duplicate'; end if;
  if (select count(*) from ai_usage where user_id=p_user_id and created_at >= day_start) >= p_limit then
    return 'limit';
  end if;
  insert into ai_usage(event_id, user_id) values(p_event_id, p_user_id);
  return 'allowed';
end $$;

create or replace function public.delete_nutrition_user(p_user_id text)
returns void language plpgsql security definer set search_path = public as $$
begin
  perform pg_advisory_xact_lock(hashtextextended(p_user_id, 0));
  delete from food_logs where user_id=p_user_id;
  delete from ai_usage where user_id=p_user_id;
  delete from users where user_id=p_user_id;
end $$;
revoke all on function public.reserve_ai_usage(text,text,integer) from public, anon, authenticated;
revoke all on function public.delete_nutrition_user(text) from public, anon, authenticated;
grant execute on function public.reserve_ai_usage(text,text,integer) to service_role;
grant execute on function public.delete_nutrition_user(text) to service_role;
-- Match the same lock used by deletion, and require the original reservation.
-- Once deletion removes ai_usage, an in-flight analysis cannot recreate a record.
create or replace function public.save_nutrition_meal(
  p_user_id text, p_event_id text, p_message_id text, p_meal jsonb
) returns void language plpgsql security definer set search_path = public as $$
begin
  perform pg_advisory_xact_lock(hashtextextended(p_user_id, 0));
  if not exists (
    select 1 from users u join ai_usage a on a.user_id=u.user_id
    where u.user_id=p_user_id and a.event_id=p_event_id
      and u.consent_version='2026-10-18' and a.created_at >= u.consented_at
  ) then raise exception 'reservation or consent no longer valid'; end if;
  insert into food_logs(user_id,message_id,food_name,calorie,protein,fat,carbs)
  values(p_user_id,p_message_id,p_meal->>'food_name',round((p_meal->>'calorie')::numeric)::integer,
    (p_meal->>'protein')::numeric,(p_meal->>'fat')::numeric,(p_meal->>'carbs')::numeric)
  on conflict(message_id) do nothing;
end $$;
revoke all on function public.save_nutrition_meal(text,text,text,jsonb) from public, anon, authenticated;
grant execute on function public.save_nutrition_meal(text,text,text,jsonb) to service_role;

-- Backend readiness check; returns no user data and is not callable with anon keys.
create or replace function public.nutrition_schema_version()
returns text language plpgsql security invoker set search_path = public as $$
begin
  perform user_id, consent_version, consented_at from users limit 0;
  perform user_id, message_id, calorie, protein, fat, carbs, created_at from food_logs limit 0;
  perform event_id, user_id, created_at from ai_usage limit 0;
  if to_regprocedure('public.accept_nutrition_consent(text)') is null
    or to_regprocedure('public.reserve_ai_usage(text,text,integer)') is null
    or to_regprocedure('public.save_nutrition_meal(text,text,text,jsonb)') is null
    or to_regprocedure('public.delete_nutrition_user(text)') is null then
    raise exception 'migration incomplete';
  end if;
  return '001_beta';
end $$;
revoke all on function public.nutrition_schema_version() from public, anon, authenticated;
grant execute on function public.nutrition_schema_version() to service_role;
notify pgrst, 'reload schema';
commit;

-- Final SQL Editor result should be a single row: schema_version = 001_beta.
select public.nutrition_schema_version() as schema_version;
